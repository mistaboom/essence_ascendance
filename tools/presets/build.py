#!/usr/bin/env python3
"""Build versioned preset downloads and their canonical wiki pages (Python 3.11+)."""
from __future__ import annotations

import argparse
import datetime
import hashlib
import html
import io
import json
import math
import os
from pathlib import Path, PurePosixPath
import re
import stat
import subprocess
import sys
import tomllib
import zipfile


REPOSITORY = "https://github.com/mistaboom/essence_ascendance"
WIKI = REPOSITORY + "/wiki/"
DOWNLOADS = REPOSITORY + "/raw/refs/heads/main/presets/downloads/"
ZIP_DATE = (2000, 1, 1, 0, 0, 0)
FIELDS = {
    "id", "revision", "pack_name", "pack_version", "minecraft", "loader",
    "config_format", "status", "tested_on", "summary", "compatibility_notes",
    "source", "page",
}
GENERATED = "<!-- Generated by tools/presets/build.py; edit presets/catalog.json and the preset sources. -->\n\n"


class PresetError(ValueError):
    """An input or generated output cannot safely be published."""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def plain_path(root: Path, path: Path) -> None:
    """Reject traversal, symlinks and Windows junctions before reading or writing."""
    try:
        path.relative_to(root)
    except ValueError as failure:
        raise PresetError("Path is outside the selected repository") from failure
    cursor = path
    while cursor != root:
        try:
            info = cursor.lstat()
        except FileNotFoundError:
            cursor = cursor.parent
            continue
        if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0):
            raise PresetError(f"Symlink or junction is not a preset source: {cursor.relative_to(root)}")
        cursor = cursor.parent


def read_text(root: Path, path: Path) -> str:
    plain_path(root, path)
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as failure:
        raise PresetError(f"Cannot read UTF-8 input {path.relative_to(root)}: {failure}") from failure


def unique_object(pairs: list[tuple[str, object]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise PresetError(f"Duplicate JSON key: {key}")
        result[key] = value
    return result


def finite(value: object) -> None:
    if isinstance(value, float) and not math.isfinite(value):
        raise PresetError("Non-finite numeric values are not allowed")
    if isinstance(value, dict):
        for child in value.values():
            finite(child)
    elif isinstance(value, list):
        for child in value:
            finite(child)


def json_value(text: str) -> object:
    try:
        result = json.loads(text, object_pairs_hook=unique_object)
    except json.JSONDecodeError as failure:
        raise PresetError(f"Invalid JSON: {failure}") from failure
    finite(result)
    return result


def private_text(text: str, name: str) -> None:
    # These checks catch accidental local provenance. They are not a credential audit.
    if re.search(r"(?i)(?:[a-z]:[\\/](?:users|documents and settings)[\\/]|/(?:home|Users|root)/|-----BEGIN [A-Z ]*PRIVATE KEY-----)", text):
        raise PresetError(f"Local user path or private key in {name}; remove private provenance before publication")


def entries(root: Path) -> list[dict]:
    catalog = json_value(read_text(root, root / "presets/catalog.json"))
    if not isinstance(catalog, dict) or set(catalog) != {"schema", "entries"} or type(catalog["schema"]) is not int or catalog["schema"] != 1:
        raise PresetError("Catalog must contain schema: 1 and entries")
    if not isinstance(catalog["entries"], list) or not catalog["entries"]:
        raise PresetError("Catalog entries must be a nonempty list")
    pairs, pages, archives = set(), set(), set()
    result = []
    for item in catalog["entries"]:
        if not isinstance(item, dict) or set(item) != FIELDS:
            raise PresetError("Each catalog entry must use exactly the documented metadata fields")
        for key in FIELDS - {"compatibility_notes"}:
            value = item[key]
            if not isinstance(value, str) or not value.strip() or value != value.strip() or any(ord(char) < 32 for char in value):
                raise PresetError(f"Metadata {key} must be a nonempty single-line string")
            private_text(value, key)
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", item["id"]):
            raise PresetError("Preset id must be a lowercase pack slug")
        if not re.fullmatch(r"[a-z0-9][a-z0-9._-]*", item["revision"]):
            raise PresetError("Preset revision must be a lowercase filename component")
        if item["source"] != f'{item["id"]}/{item["revision"]}':
            raise PresetError("Preset source must be <id>/<revision> beneath presets/")
        if not re.fullmatch(r"Preset-[A-Za-z0-9]+(?:-[A-Za-z0-9]+)*", item["page"]):
            raise PresetError("Detail page must be a safe Preset-... wiki filename stem")
        try:
            if datetime.date.fromisoformat(item["tested_on"]).isoformat() != item["tested_on"]:
                raise ValueError("Use YYYY-MM-DD")
        except ValueError as failure:
            raise PresetError("tested_on must be a real YYYY-MM-DD date") from failure
        notes = item["compatibility_notes"]
        if not isinstance(notes, list) or any(not isinstance(note, str) or not note.strip() or any(ord(char) < 32 for char in note) for note in notes):
            raise PresetError("compatibility_notes must be a list of nonempty single-line strings")
        for note in notes:
            private_text(note, "compatibility_notes")
        pair = (item["id"], item["revision"])
        archive = archive_name(item).casefold()
        if pair in pairs or item["page"].casefold() in pages or archive in archives:
            raise PresetError("Duplicate preset revision, wiki page or archive filename")
        pairs.add(pair)
        pages.add(item["page"].casefold())
        archives.add(archive)
        result.append(item)
    return result


def archive_name(entry: dict) -> str:
    return f'{entry["id"]}-{entry["revision"]}.zip'


def allowed_payload(name: str) -> bool:
    path = PurePosixPath(name)
    if any(not re.fullmatch(r"[A-Za-z0-9_.-]+", part) or part in {".", ".."} for part in path.parts):
        return False
    if len(path.parts) >= 2 and path.parts[0] == "config" and path.suffix == ".toml":
        return True
    # KubeGroovy supplies a virtual server datapack from this directory. Keep
    # executable scripts, client assets and arbitrary loader files out of presets.
    if len(path.parts) >= 5 and path.parts[:2] == ("kubegroovy", "data") and path.suffix == ".json":
        return True
    return len(path.parts) >= 3 and path.parts[0] == "datapacks" and (
        len(path.parts) == 3 and path.name == "pack.mcmeta"
        or len(path.parts) >= 5 and path.parts[2] == "data" and path.suffix == ".json"
    )


def payload(root: Path, entry: dict) -> dict[str, bytes]:
    source = root / "presets" / entry["source"]
    files = source / "files"
    result = {}
    for name in ("README.txt", "LICENSE.txt"):
        text = read_text(root, source / name)
        if not text.strip():
            raise PresetError(f'Empty {name} for {entry["source"]}')
        private_text(text, name)
        # Preserve exact input bytes, including their chosen line endings.
        result[name] = (source / name).read_bytes()
    plain_path(root, files)
    if not files.is_dir():
        raise PresetError(f'Missing files/ payload for {entry["source"]}')
    folded = {"readme.txt", "license.txt", "sha256sums.txt"}
    for current, directories, names in os.walk(files, followlinks=False):
        for directory in directories:
            plain_path(root, Path(current) / directory)
        directories.sort()
        for filename in sorted(names):
            file = Path(current) / filename
            plain_path(root, file)
            name = file.relative_to(files).as_posix()
            if not allowed_payload(name):
                raise PresetError(f"Disallowed payload file: {name}; only editable TOML settings and datapack JSON are distributed")
            if name.casefold() in folded:
                raise PresetError(f"Duplicate case-insensitive archive path: {name}")
            folded.add(name.casefold())
            text = read_text(root, file)
            private_text(text, name)
            try:
                value = tomllib.loads(text) if file.suffix == ".toml" else json_value(text)
                finite(value)
            except (tomllib.TOMLDecodeError, PresetError) as failure:
                raise PresetError(f"Invalid preset input {name}: {failure}") from failure
            result[name] = file.read_bytes()
    if len(result) == 2:
        raise PresetError(f'Empty payload for {entry["source"]}')
    packs = {PurePosixPath(name).parts[1] for name in result if name.startswith("datapacks/")}
    for pack in packs:
        if f"datapacks/{pack}/pack.mcmeta" not in result:
            raise PresetError(f"Datapack {pack} needs its own pack.mcmeta")
    sums = "".join(f"{sha256(data)}  {name}\n" for name, data in sorted(result.items()))
    result["SHA256SUMS.txt"] = sums.encode("utf-8")
    return result


def zip_bytes(files: dict[str, bytes]) -> bytes:
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, ZIP_DATE)
            info.create_system = 3
            info.external_attr = (stat.S_IFREG | 0o644) << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, data, compresslevel=9)
    return output.getvalue()


def existing_archive(data: bytes, files: dict[str, bytes]) -> bool:
    """Keep an already-built revision byte-for-byte, including across zlib versions."""
    try:
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            info = archive.infolist()
            return (
                not archive.comment
                and [part.filename for part in info] == sorted(files)
                and all(part.date_time == ZIP_DATE and part.file_size == len(files[part.filename])
                        and part.create_system == 3 and part.external_attr == (stat.S_IFREG | 0o644) << 16
                        and part.compress_type == zipfile.ZIP_DEFLATED
                        and not part.comment and not part.extra and part.flag_bits == 0
                        and part.orig_filename == part.filename
                        and archive.read(part) == files[part.filename] for part in info)
            )
    except (zipfile.BadZipFile, RuntimeError, ValueError, OSError):
        return False


def is_tracked(root: Path, path: Path) -> bool:
    if not (root / ".git").exists():
        return False
    try:
        check = subprocess.run(["git", "-C", str(root), "ls-files", "--error-unmatch", "--", path.relative_to(root).as_posix()], capture_output=True)
    except OSError as failure:
        raise PresetError("Cannot establish whether the existing archive is tracked; refusing replacement") from failure
    if check.returncode not in (0, 1):
        raise PresetError("Cannot establish whether the existing archive is tracked; refusing replacement")
    return check.returncode == 0


def markdown(value: str) -> str:
    value = html.escape(value, quote=False)
    for char in ("\\", "|", "`", "[", "]"):
        value = value.replace(char, "\\" + char)
    return value


def table(items: list[dict]) -> str:
    text = "| Pack | Pack version | Minecraft | Loader | Preset | Status | Download |\n| --- | --- | --- | --- | --- | --- | --- |\n"
    for item in items:
        values = [markdown(item[key]) for key in ("pack_name", "pack_version", "minecraft", "loader")]
        values += [f'[{markdown(item["revision"])}]({WIKI}{item["page"]})', markdown(item["status"]), f'[ZIP]({DOWNLOADS}{archive_name(item)})']
        text += "| " + " | ".join(values) + " |\n"
    return text


def natural(value: str) -> tuple:
    return tuple((0, int(part)) if part.isdigit() else (1, part.casefold()) for part in re.split(r"(\d+)", value))


def catalog_page(items: list[dict]) -> str:
    groups: dict[str, list[dict]] = {}
    for item in items:
        groups.setdefault(item["id"], []).append(item)
    latest, older = [], []
    for group in sorted(groups.values(), key=lambda group: group[0]["pack_name"].casefold()):
        ordered = sorted(group, key=lambda item: (item["tested_on"], natural(item["revision"])), reverse=True)
        latest.append(ordered[0])
        older.extend(ordered[1:])
    text = GENERATED + "# Configuration preset downloads\n\n"
    text += f"[Home]({WIKI}Home) · [Configuration]({WIKI}Configuration) · [Rebuilding]({WIKI}Balance-Generation)\n\n"
    text += "Download editable Essence Ascendance settings prepared for specific modpacks. Each preset has its own pack version, test status, installation instructions and checksum. Read its details before installing.\n\n"
    text += "## Available presets\n\n" + table(latest)
    if older:
        text += "\n## Previous versions and revisions\n\nOlder downloads remain available for their original packs.\n\n" + table(older)
    text += "\n## Using a preset\n\n"
    text += "1. Choose the preset for your pack version and loader, and read its compatibility notes. A playtest preset is still being evaluated in normal gameplay.\n"
    text += "2. Install the supplied editable configuration files and any included datapack using that preset's instructions.\n"
    text += "3. Rebuild and validate balance on the server or integrated single-player server, then check the results in the Ascendance Archive. Restarting alone does not replace an existing generated profile.\n\n"
    text += "These downloads contain configuration inputs, not mod jars, worlds, player records or a cached generated balance. Using them in a different pack is a starting point for your own tuning, not a claim of compatibility.\n\n"
    text += f"New packs and retuned versions are added as separate entries. [Maintainer instructions and editable sources]({REPOSITORY}/tree/main/presets) explain how to add another preset without replacing existing downloads.\n"
    return text


def detail_page(item: dict, files: dict[str, bytes], archive: bytes) -> str:
    text = GENERATED + f'# {markdown(item["pack_name"])} — {markdown(item["revision"])}\n\n'
    text += f"[All configuration presets]({WIKI}Config-Presets) · [Download ZIP]({DOWNLOADS}{archive_name(item)})\n\n"
    text += markdown(item["summary"]) + "\n\n| Detail | Value |\n| --- | --- |\n"
    for label, key in (("Pack version", "pack_version"), ("Minecraft", "minecraft"), ("Loader", "loader"), ("Configuration tested with", "config_format"), ("Preset revision", "revision"), ("Test status", "status"), ("Tested on", "tested_on")):
        text += f"| {label} | {markdown(item[key])} |\n"
    if item["compatibility_notes"]:
        text += "\n## Compatibility notes\n\n"
        text += "".join("- " + markdown(note) + "\n" for note in item["compatibility_notes"])
    # Wiki sources use LF in Git; preserve the authored bytes only in the ZIP.
    readme = files["README.txt"].decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")
    text += "\n## Installation and notes\n\n" + readme.rstrip() + "\n"
    text += "\n## Download verification\n\n"
    text += f'Archive: `{archive_name(item)}`\n\nSHA-256:\n\n```text\n{sha256(archive)}\n```\n\n'
    text += "The archive includes `SHA256SUMS.txt` for the individual files.\n\n### Included files\n\n"
    text += "".join(f"- `{name}`\n" for name in sorted(files))
    return text


def build(root: Path, *, write: bool = False, replace_unpublished: bool = False) -> dict:
    root = root.resolve()
    catalog = entries(root)
    outputs: dict[Path, bytes] = {}
    archive_sums = []
    for item in catalog:
        files = payload(root, item)
        archive = zip_bytes(files)
        destination = root / "presets/downloads" / archive_name(item)
        plain_path(root, destination)
        if not destination.exists() and is_tracked(root, destination):
            raise PresetError(f"Tracked archive is missing: {destination.name}. Restore its recorded bytes from Git; do not rebuild a published revision.")
        if destination.exists():
            if not destination.is_file():
                raise PresetError(f"Archive destination is not a file: {destination.relative_to(root)}")
            current = destination.read_bytes()
            if existing_archive(current, files):
                archive = current
            elif not (write and replace_unpublished and not is_tracked(root, destination)):
                raise PresetError(f"Existing archive differs from its inputs: {destination.name}. Add a new preset revision; tracked downloads are immutable.")
        outputs[destination] = archive
        archive_sums.append(f"{sha256(archive)}  {destination.name}\n")
        outputs[root / "docs/wiki" / (item["page"] + ".md")] = detail_page(item, files, archive).encode("utf-8")
    outputs[root / "presets/downloads/SHA256SUMS.txt"] = "".join(sorted(archive_sums, key=lambda line: line.split("  ", 1)[1])).encode("utf-8")
    outputs[root / "docs/wiki/Config-Presets.md"] = catalog_page(catalog).encode("utf-8")
    stale = []
    for path, content in outputs.items():
        plain_path(root, path)
        if path.exists() and not path.is_file():
            raise PresetError(f"Output destination is not a file: {path.relative_to(root)}")
        if not path.exists() or path.read_bytes() != content:
            stale.append(path)
    if stale and not write:
        raise PresetError("Missing or stale generated files: " + ", ".join(path.relative_to(root).as_posix() for path in stale))
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(outputs[path])
    return {"presets": len(catalog), "outputs": len(outputs), "updated": len(stale)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--write", action="store_true", help="Build new downloads and update generated wiki pages")
    modes.add_argument("--check", action="store_true", help="Validate inputs and generated files without writing anything")
    parser.add_argument("--replace-unpublished", action="store_true", help="Permit replacing a changed archive only while it is untracked by Git")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2], help=argparse.SUPPRESS)
    args = parser.parse_args()
    if args.replace_unpublished and not args.write:
        parser.error("--replace-unpublished requires --write")
    try:
        result = build(args.root, write=args.write, replace_unpublished=args.replace_unpublished)
    except (PresetError, OSError) as failure:
        print(f"Preset build failed: {failure}", file=sys.stderr)
        return 1
    print(f'Preset catalog verified: {result["presets"]} presets, {result["outputs"]} outputs, {result["updated"]} updated')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
